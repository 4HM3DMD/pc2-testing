//! Watermark compositor — embeds buyer identity into rendered output.
//!
//! Applied to all render-mode output (images, text, PDFs).
//! The watermark is semi-transparent text overlaid on the rendered pixels.

#[cfg(feature = "image-render")]
use image::{Rgba, RgbaImage};

/// Overlay a text watermark onto an RGBA image.
///
/// Places semi-transparent white text with dark shadow at the bottom-right.
/// This is a simple pixel-based approach that doesn't require font rendering
/// for the watermark itself (uses a built-in bitmap font).
#[cfg(feature = "image-render")]
pub fn apply_watermark(img: &mut RgbaImage, text: &str) {
    let (w, h) = img.dimensions();
    if w < 100 || h < 50 || text.is_empty() {
        return;
    }

    let char_w: u32 = 6;
    let char_h: u32 = 10;
    let padding: u32 = 10;
    let text_len = text.len() as u32;
    let total_text_w = text_len * char_w;

    if total_text_w + padding * 2 > w {
        return;
    }

    let start_x = w - total_text_w - padding;
    let start_y = h - char_h - padding;

    // Draw a semi-transparent dark background strip
    for y in start_y.saturating_sub(2)..=(start_y + char_h + 1).min(h - 1) {
        for x in start_x.saturating_sub(4)..=(start_x + total_text_w + 3).min(w - 1) {
            let pixel = img.get_pixel_mut(x, y);
            *pixel = Rgba([
                (pixel[0] as u16 * 128 / 256) as u8,
                (pixel[1] as u16 * 128 / 256) as u8,
                (pixel[2] as u16 * 128 / 256) as u8,
                pixel[3],
            ]);
        }
    }

    // Draw text using simple bitmap characters
    for (i, ch) in text.chars().enumerate() {
        let glyph = get_bitmap_char(ch);
        let cx = start_x + (i as u32) * char_w;
        for (row, bits) in glyph.iter().enumerate() {
            for col in 0..char_w {
                if bits & (1 << (char_w - 1 - col)) != 0 {
                    let px = cx + col;
                    let py = start_y + row as u32;
                    if px < w && py < h {
                        let pixel = img.get_pixel_mut(px, py);
                        // Semi-transparent white
                        *pixel = Rgba([
                            ((pixel[0] as u16 + 200) / 2) as u8,
                            ((pixel[1] as u16 + 200) / 2) as u8,
                            ((pixel[2] as u16 + 200) / 2) as u8,
                            pixel[3],
                        ]);
                    }
                }
            }
        }
    }
}

